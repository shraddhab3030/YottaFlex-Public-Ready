def annotations(sql: str) -> dict:
    result = {}
    purpose = ""
    current = None
    for line in sql.splitlines():
        if line.startswith("-- table: "):
            purpose = line.removeprefix("-- table: ")
        match = re.match(r"CREATE TABLE (\w+) \(", line)
        if match:
            current = match.group(1)
            result[current] = {"purpose": purpose, "fields": {}, "checks": []}
        elif re.fullmatch(r"\) STRICT(?:, WITHOUT ROWID)?;", line):
            current = None
        elif current:
            field = re.match(r"    (\w+) (?:TEXT|INTEGER)\b", line)
            if field:
                definition, note = line.strip().split(" -- ", 1)
                meaning, units = note.split(" | ", 1)
                result[current]["fields"][field.group(1)] = (definition.rstrip(","), meaning, units)
            elif line.strip().startswith("CHECK ("):
                result[current]["checks"].append(line.strip().rstrip(","))
    return result


def render_dictionary() -> str:
    sql = SCHEMA_PATH.read_text()
    notes = annotations(sql)
    content = [HEADER]
    with closing(connect()) as db:
        initialize(db)
        for table, note in notes.items():
            columns = list(db.execute(f'PRAGMA table_info("{table}")'))
            if {row["name"] for row in columns} != set(note["fields"]):
                raise ValueError(f"Missing column annotation for {table}")
            primary = [row["name"] for row in sorted(columns, key=lambda row: row["pk"]) if row["pk"]]
            fks = list(db.execute(f'PRAGMA foreign_key_list("{table}")'))
            unique = []
            for index in db.execute(f'PRAGMA index_list("{table}")'):
                if index["unique"]:
                    index_columns = [row["name"] for row in db.execute(f'PRAGMA index_info("{index["name"]}")')]
                    predicate = ""
                    if index["partial"]:
                        index_sql = db.execute("SELECT sql FROM sqlite_schema WHERE name=?", (index["name"],)).fetchone()[0]
                        predicate = " WHERE " + index_sql.split(" WHERE ", 1)[1]
                    unique.append((index_columns, predicate))
            content += [f"### {table}\n\n{note['purpose']}.\n\n",
                "| Field | SQLite type | Required | Allowed values | Units | Default | PK / FK | Uniqueness | Validation | Meaning / purpose |\n",
                "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |\n"]
            for column in columns:
                name = column["name"]
                definition, meaning, units = note["fields"][name]
                checks = re.findall(r"CHECK \((.*)\)", definition)
                table_checks = [item for item in note["checks"] if re.search(rf"\b{re.escape(name)}\b", item)]
                references = [f"{fk['table']}.{fk['to']} (FK group {fk['id']})" for fk in fks if fk["from"] == name]
                keys = (["PK(" + ", ".join(primary) + ")"] if column["pk"] else []) + references
                uniqueness = ["UNIQUE(" + ", ".join(fields) + ")" + condition for fields, condition in unique if name in fields]
                if column["pk"]:
                    # INTEGER PRIMARY KEY can alias rowid without index_list entry.
                    uniqueness.insert(0, "PRIMARY KEY(" + ", ".join(primary) + ")")
                allowed = "; ".join(checks) if checks else ("existing referenced key" if references else "non-null value" if column["notnull"] else "value or NULL")
                validation = "; ".join(checks + table_checks) or "SQLite type/nullability and keys above"
                if name in primary:
                    validation += "; immutable identity"
                values = [name, column["type"], "yes" if column["notnull"] else "no", allowed,
                    units, column["dflt_value"] if column["dflt_value"] is not None else "none (no implicit value)",
                    "; ".join(keys) or "none", "; ".join(uniqueness) or "not unique alone", validation, meaning]
                content.append("| " + " | ".join(str(value).replace("|", "\\|").replace("\n", " ") for value in values) + " |\n")
            content.append("\n")
    content += ["## Exact schema DDL and trigger/index constraints\n\n```sql\n", sql, "```\n"]
    return "".join(content)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed dictionary is stale")
    args = parser.parse_args()
    rendered = render_dictionary()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != rendered:
            print("FAIL: docs/data-dictionary.md is missing or differs from implemented schema")
            return 1
        print("PASS: every dictionary field/constraint matches annotated SQL and SQLite metadata")
    else:
        OUTPUT.write_text(rendered)
        print("Wrote docs/data-dictionary.md from actual schema")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
